#!/usr/bin/env python3
"""Generate the refresh silhouette from the approved app icon. Use --check in CI."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
master = root / 'Design/AppIcons/oath-solid-blue.svg'
paths = ET.fromstring(master.read_text()).findall('{http://www.w3.org/2000/svg}path')
lines = []
for path in paths:
    tokens = re.findall(r'[MCZ]|-?\d+(?:\.\d+)?', path.attrib['d'])
    index = 0
    while index < len(tokens):
        command = tokens[index]
        index += 1
        count = {'M': 2, 'C': 6, 'Z': 0}[command]
        points = tokens[index:index + count]
        index += count
        if command == 'M':
            lines.append(f'        path.move(to: CGPoint(x: {points[0]}, y: {points[1]}))')
        elif command == 'C':
            a, b, c, d, e, f = points
            lines.append(f'        path.addCurve(to: CGPoint(x: {e}, y: {f}), control1: CGPoint(x: {a}, y: {b}), control2: CGPoint(x: {c}, y: {d}))')
        else:
            lines.append('        path.closeSubpath()')
source = '''import SwiftUI

// Generated by Tools/BuildRefreshMark.py from Design/AppIcons/oath-solid-blue.svg.
// Keep the same silhouette as the installed icon; do not redraw the rings.
struct OathRefreshMark: Shape {
    private static let outline: Path = {
        var path = Path()
''' + '\n'.join(lines) + '''
        return path
    }()

    func path(in rect: CGRect) -> Path {
        let bounds = Self.outline.boundingRect
        let scale = min(rect.width / bounds.width, rect.height / bounds.height)
        guard scale.isFinite, scale > 0 else { return Path() }
        return Self.outline.applying(CGAffineTransform(
            a: scale, b: 0, c: 0, d: scale,
            tx: rect.midX - bounds.midX * scale, ty: rect.midY - bounds.midY * scale
        ))
    }
}
'''
target = root / 'Packages/OathNativeRefresh/Sources/OathNativeRefresh/OathRefreshMark.swift'
if '--check' in sys.argv:
    assert target.read_text() == source, 'Refresh logo must match the approved app icon; run Tools/BuildRefreshMark.py'
else:
    target.write_text(source)
print('Refresh silhouette matches the approved app icon.')
