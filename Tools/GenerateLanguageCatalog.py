#!/usr/bin/env python3
"""Refresh the offline language registry without manufacturing translations.

Reads Design/Localization/languages.json, preserves supported reviewed catalog
values and prunes unsupported resources. Fails before writing any file if a
required translation is missing, unfinished, structurally invalid or an
unreviewed English copy. Supply translations first; never seed English values.
No translation service or network request is used by this tool.
"""
from pathlib import Path
import json
import re

from CheckLocalizationCatalog import audit_catalog

ROOT = Path(__file__).resolve().parent.parent


def generate(root: Path = ROOT) -> None:
    entries = json.loads((root / 'Design/Localization/languages.json').read_text())
    assert len({entry['code'] for entry in entries}) == len(entries), 'Duplicate language code'
    assert len({entry['nameKey'] for entry in entries}) == len(entries), 'Duplicate language name key'
    supported_codes = {entry['code'] for entry in entries}
    name_keys = {entry['nameKey'] for entry in entries}
    assert 'en' in supported_codes, 'English is the development and fallback language'
    shared_path = root / 'Design/Localization/shared-values.json'
    shared = json.loads(shared_path.read_text()) if shared_path.exists() else {}

    # Validate every proposed catalog before touching catalogs, Swift or manifest.
    catalogs = {}
    errors = []
    for name in ['Localizable', 'InfoPlist', 'LanguageNames']:
        path = root / f'OathApp/Resources/{name}.xcstrings'
        data = json.loads(path.read_text())
        if name == 'LanguageNames':
            data['strings'] = {key: entry for key, entry in data['strings'].items() if key in name_keys}
            assert set(data['strings']) == name_keys, 'Add reviewed display names for every supported language'
        for entry in data['strings'].values():
            if 'localizations' in entry:
                entry['localizations'] = {code: value for code, value in entry['localizations'].items() if code in supported_codes}
        errors.extend(audit_catalog(name, data, supported_codes, shared.get(name, {})))
        catalogs[path] = data
    if errors:
        raise ValueError('Catalog generation stopped before writing; complete the translations first:\n' + '\n'.join(errors[:30]) + f'\n{len(errors)} total findings. Run Tools/CheckLocalizationCatalog.py --json for details.')

    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ['// Generated by Tools/GenerateLanguageCatalog.py from the reviewed language registry.',
             'import Foundation', '', 'extension OathLanguage {', '    static let definitions: [Definition] = [']
    for entry in entries:
        args = ', '.join(f'{key}: {quote(value)}' for key, value in [
            ('code', entry['code']), ('localeIdentifier', entry['locale']), ('englishName', entry['englishName']),
            ('nativeName', entry['nativeName']), ('nameKey', entry['nameKey']), ('flag', entry['flag'])])
        lines.append('        .init(' + args + '),')
    lines += ['    ]', '}', '']
    (root / 'OathAtmosphere/Localization/OathLanguageCatalog.swift').write_text('\n'.join(lines))
    for path, data in catalogs.items():
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    project = root / 'project.yml'
    text = re.sub(r'CFBundleLocalizations: \[[^\n]+\]',
                  'CFBundleLocalizations: [' + ', '.join(entry['code'] for entry in entries) + ']', project.read_text())
    project.write_text(text)
    print(f'Generated exactly {len(entries)} language choices; unsupported resources removed and reviewed translations retained.')


if __name__ == '__main__':
    generate()
